def _state_path(run: str) -> str:
    return os.path.join(run, "workspace", "state.json")


def _version_path(run: str, n: int) -> str:
    return os.path.join(run, "workspace", "versions", f"v{n:04d}.json")


def _write_version(run: str, n: int, files: dict, complete: bool = True):
    _write(_version_path(run, n), json.dumps({"complete": complete, "files": files}))


def _read_version(run: str, n: int) -> tuple[dict, bool]:
    path = _version_path(run, n)
    if not os.path.exists(path):
        raise WorkspaceError("That version doesn't exist.", 404)
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data["files"], data.get("complete", True)


def save_state(run: str, state: dict):
    _write(_state_path(run), json.dumps(state, indent=1))


def _migrate(run: str, state: dict) -> dict:
    """Older editor states kept only the main file per version; keep them as partial snapshots."""
    for v in state.get("versions", []):
        old = os.path.join(run, "workspace", "versions", f"v{v['n']:04d}.tex")
        if os.path.exists(old) and not os.path.exists(_version_path(run, v["n"])):
            _write_version(run, v["n"], {state["main"]: _read(old)}, complete=False)
    n = max([v["n"] for v in state.get("versions", [])] or [0]) + 1
    _write_version(run, n, _snapshot(run))
    state.setdefault("versions", []).append({"n": n, "note": "All project files", "time": time.time()})
    state.update(format=2, version=n)
    save_state(run, state)
    return state


def load_state(run: str, main: str | None = None) -> dict:
    path = _state_path(run)
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            state = json.load(f)
        if state.get("format") != 2:
            state = _migrate(run, state)
        if not os.path.exists(_abs(run, state["main"])):  # main file was deleted or renamed outside the app
            state["main"] = _find_main(run) or state["main"]
        return state
    main = main or _find_main(run)
    if not main:
        raise WorkspaceError("No .tex file with \\documentclass was found in this project.", 404)
    state = {"format": 2, "main": main, "messages": [], "version": 1, "cost": 0.0, "compile": None,
             "versions": [{"n": 1, "note": "Original", "time": time.time()}]}
    _write_version(run, 1, _snapshot(run))
    save_state(run, state)
    return state


def _commit(run: str, state: dict, note: str) -> int:
    n = max(v["n"] for v in state["versions"]) + 1
    _write_version(run, n, _snapshot(run))
    state["versions"].append({"n": n, "note": note[:120], "time": time.time()})
    state["version"] = n
    return n


def _event(state: dict, text: str, version: int | None = None):
    msg = {"role": "event", "text": text, "time": time.time()}
    if version:
        msg["version"] = version
    state["messages"].append(msg)


def _diff(old: dict, new: dict) -> dict:
    lines, added, removed, changed = [], 0, 0, []
    for path in sorted(set(old) | set(new), key=str.lower):
        a, b = old.get(path), new.get(path)
        if a == b:
            continue
        changed.append(path)
        label = " (new file)" if a is None else " (deleted)" if b is None else ""
        body = list(difflib.unified_diff((a or "").splitlines(), (b or "").splitlines(), lineterm="", n=1))[2:]
        added += sum(1 for l in body if l.startswith("+"))
        removed += sum(1 for l in body if l.startswith("-"))
        lines += [f"### {path}{label}"] + body
    return {"added": added, "removed": removed, "files": changed, "text": "\n".join(lines[:600])}


