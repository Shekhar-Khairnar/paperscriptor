PID_RE = re.compile(r"^\d{8}-\d{6}-[0-9a-f]{8}$")
TEXT_EXT = {".tex", ".bib", ".sty", ".cls", ".bst", ".txt", ".md", ".csv", ".tsv", ".json", ".cfg", ".def", ".clo",
            ".bbx", ".cbx", ".lbx", ".dtx", ".ins", ".ltx", ".tikz", ".yaml", ".yml", ".bbl"}
BUILD_EXT = (".aux", ".log", ".out", ".blg", ".fls", ".fdb_latexmk", ".synctex.gz", ".toc", ".lof", ".lot", ".xdv",
             ".nav", ".snm", ".vrb", ".run.xml", ".bcf", ".tmp")
IMAGE_EXT = {".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp"}
MAX_TEXT = 2_000_000                 # larger text files are not versioned or edited
MAX_UPLOAD = 50 * 1024 * 1024
MAX_CONTEXT_CHARS = 600_000          # project text sent to the model per request
MAX_INPUT_CHARS = 150_000
HISTORY_TURNS = 8
_busy: dict[str, pipeline.Job] = {}
_busy_guard = threading.Lock()


class WorkspaceError(Exception):
    def __init__(self, msg: str, code: int = 400):
        super().__init__(msg)
        self.code = code


