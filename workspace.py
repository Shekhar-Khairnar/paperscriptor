def _check_main(state: dict, rel: str, text: str):
    if rel == state["main"] and ("\\documentclass" not in text or "\\end{document}" not in text):
        raise WorkspaceError(f"{rel} is the main file, and the change would remove \\documentclass or "
                             "\\end{document}, so it was not saved.")


def save_file(run: str, rel: str, text: str) -> dict:
    state = load_state(run)
    rel = safe_rel(rel)
    if not is_text(rel):
        raise WorkspaceError(f"'{rel}' can't be edited as text.")
    text = text.replace("\r\n", "\n")
    _check_main(state, rel, text)
    path = _abs(run, rel)
    if not os.path.exists(path) or _read(path) != text:
        _write(path, text)
        n = _commit(run, state, f"Edited {rel}")
        _event(state, f"You edited {rel} (version {n}).", n)
        save_state(run, state)
    return summary(run)


def new_file(run: str, rel: str) -> dict:
    state = load_state(run)
    rel = safe_rel(rel)
    if not is_text(rel):
        raise WorkspaceError("New files must be text files, such as .tex, .bib or .md.")
    path = _abs(run, rel)
    if os.path.exists(path):
        raise WorkspaceError(f"'{rel}' already exists.")
    _write(path, f"% {rel}\n" if rel.endswith(".tex") else "")
    n = _commit(run, state, f"Created {rel}")
    _event(state, f"Created {rel} (version {n}).", n)
    save_state(run, state)
    return summary(run)


def delete_file(run: str, rel: str) -> dict:
    state = load_state(run)
    rel = safe_rel(rel)
    if rel == state["main"]:
        raise WorkspaceError("This is the main file. Choose another main file first.")
    path = _abs(run, rel)
    if not os.path.isfile(path):
        raise WorkspaceError(f"'{rel}' doesn't exist.", 404)
    os.remove(path)
    n = _commit(run, state, f"Deleted {rel}")
    _event(state, f"Deleted {rel} (version {n})." + ("" if is_text(rel) else " Undo can't bring back non-text files."), n)
    save_state(run, state)
    return summary(run)


def upload(run: str, uploads: list[tuple[str, bytes]], folder: str = "") -> dict:
    state = load_state(run)
    if not uploads:
        raise WorkspaceError("Choose at least one file.")
    if sum(len(d) for _, d in uploads) > MAX_UPLOAD:
        raise WorkspaceError("The upload is larger than 50 MB.")
    folder = safe_rel(folder) if folder.strip("/ ") else ""
    names = []
    for name, data in uploads:
        rel = safe_rel(posixpath.join(folder, name.replace("\\", "/"))) if folder else safe_rel(name)
        path = _abs(run, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
        names.append(rel)
    n = _commit(run, state, f"Uploaded {len(names)} file(s)")
    shown = ", ".join(names[:4]) + (f" and {len(names) - 4} more" if len(names) > 4 else "")
    _event(state, f"Uploaded {shown} (version {n}).", n)
    save_state(run, state)
    return summary(run)


def set_main(run: str, rel: str) -> dict:
    state = load_state(run)
    rel = safe_rel(rel)
    if not rel.lower().endswith(".tex") or not os.path.isfile(_abs(run, rel)):
        raise WorkspaceError("Choose a .tex file.")
    if rel != state["main"]:
        state["main"], state["compile"] = rel, None
        _event(state, f"Main file is now {rel}.")
        save_state(run, state)
    return summary(run)


def restore(run: str, n: int) -> dict:
    state = load_state(run)
    files, complete = _read_version(run, n)
    current = _snapshot(run)
    for rel, text in files.items():
        _write(_abs(run, rel), text)
    if complete:
        for rel in current:
            if rel not in files and rel != state["main"]:
                os.remove(_abs(run, rel))
    if state["main"] not in files and complete:
        state["main"] = _find_main(run) or state["main"]
    m = _commit(run, state, f"Restored version {n}")
    _event(state, f"Went back to version {n} (saved as version {m}).", m)
    save_state(run, state)
    return summary(run)


