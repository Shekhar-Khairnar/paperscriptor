def run_dir(runs_root: str, pid: str) -> str:
    if not PID_RE.match(pid or ""):
        raise WorkspaceError("Unknown project.", 404)
    path = os.path.join(runs_root, pid)
    if not os.path.isdir(os.path.join(path, "paper")):
        raise WorkspaceError("This project has no paper yet.", 404)
    return path


def _paper(run: str) -> str:
    return os.path.join(run, "paper")


def safe_rel(rel: str) -> str:
    """Normalise a project-relative path; refuse anything that could leave the project folder."""
    rel = (rel or "").replace("\\", "/").strip().strip("/")
    norm = posixpath.normpath(rel) if rel else ""
    parts = norm.split("/")
    if (not norm or norm == "." or norm.startswith("../") or norm == ".." or ":" in parts[0]
            or any(p.startswith(".") or p == "__MACOSX" for p in parts)):
        raise WorkspaceError(f"'{rel}' is not a valid file name.")
    return norm


def _abs(run: str, rel: str) -> str:
    return os.path.join(_paper(run), *safe_rel(rel).split("/"))


def _ext(rel: str) -> str:
    low = rel.lower()
    return ".synctex.gz" if low.endswith(".synctex.gz") else os.path.splitext(low)[1]


def is_text(rel: str) -> bool:
    return _ext(rel) in TEXT_EXT


def _read(path: str, limit: int | None = None) -> str:
    if not os.path.exists(path):
        return ""
    with open(path, encoding="utf-8", errors="replace") as f:
        text = f.read()
    return text[:limit] if limit else text


def _write(path: str, text: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, path)


def _all_files(run: str) -> list[str]:
    paper, out = _paper(run), []
    for root, dirs, files in os.walk(paper):
        dirs[:] = [d for d in dirs if not d.startswith(".") and d != "__MACOSX"]
        for name in files:
            if name.startswith(".") or name.endswith(".tmp"):
                continue
            out.append(os.path.relpath(os.path.join(root, name), paper).replace("\\", "/"))
    return sorted(out, key=str.lower)


def _hidden(rel: str, all_set: set) -> bool:
    """Build outputs: aux/log files and the PDF next to a .tex file of the same name."""
    low = rel.lower()
    if low.endswith(BUILD_EXT):
        return True
    if low.endswith(".bbl"):  # generated by bibtex, unless the project ships it instead of a .bib
        return any(f.lower().endswith(".bib") for f in all_set)
    if low.endswith(".pdf"):
        stem = rel[:-4]
        if stem + ".tex" in all_set:
            return True
        if "/" not in rel:  # compiled output of a main file that lives in a subfolder
            return any(f.endswith("/" + stem + ".tex") for f in all_set)
    return False


def list_files(run: str) -> list[dict]:
    files = _all_files(run)
    all_set = set(files)
    out = []
    for rel in files:
        if _hidden(rel, all_set):
            continue
        ext = _ext(rel)
        kind = ("tex" if ext == ".tex" else "bib" if ext == ".bib" else "text" if ext in TEXT_EXT
                else "image" if ext in IMAGE_EXT else "pdf" if ext == ".pdf" else "other")
        size = os.path.getsize(_abs(run, rel))
        out.append({"path": rel, "size": size, "kind": kind, "editable": kind in ("tex", "bib", "text") and size <= MAX_TEXT})
    return out


def _snapshot(run: str) -> dict[str, str]:
    snap = {}
    for f in list_files(run):
        if f["editable"]:
            snap[f["path"]] = _read(_abs(run, f["path"]))
    return snap


def _main_candidates(run: str) -> list[str]:
    return [f["path"] for f in list_files(run)
            if f["kind"] == "tex" and "\\documentclass" in _read(_abs(run, f["path"]), 30_000)]


def _find_main(run: str) -> str | None:
    cands = _main_candidates(run)
    if not cands:
        return None
    if "main.tex" in cands:
        return "main.tex"
    try:
        return ingest._pick_main({c: _read(_abs(run, c), 30_000).encode() for c in cands})
    except ingest.InputError:
        return cands[0]


