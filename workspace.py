def _braced(text: str, start: int) -> str:
    depth = 0
    for i in range(start, min(len(text), start + 2000)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
    return ""


def title_of(tex: str) -> str:
    m = re.search(r"\\title\s*(\[[^\]]*\])?\s*\{", tex)
    if not m:
        return ""
    t = _braced(tex, m.end() - 1)
    t = re.sub(r"\\(thanks|footnote)\s*\{.*", "", t, flags=re.S)
    t = re.sub(r"\\\\|\\newline", " ", t)
    t = re.sub(r"\\[a-zA-Z]+\*?(\[[^\]]*\])?", "", t)
    t = re.sub(r"[{}~]", " ", t)
    return re.sub(r"\s+", " ", t).strip()[:140]


def list_projects(runs_root: str) -> list[dict]:
    out = []
    if not os.path.isdir(runs_root):
        return out
    for pid in sorted(os.listdir(runs_root), reverse=True):
        run = os.path.join(runs_root, pid)
        if not PID_RE.match(pid) or not os.path.isdir(_paper(run)):
            continue
        main = None
        try:
            with open(_state_path(run), encoding="utf-8") as f:
                main = json.load(f).get("main")
        except (OSError, ValueError):
            main = "main.tex" if os.path.exists(os.path.join(_paper(run), "main.tex")) else _find_main(run)
        if not main or not os.path.exists(_abs(run, main)):
            continue
        tex = _read(_abs(run, main), 30_000)
        if "\\documentclass" not in tex:
            continue
        out.append({
            "id": pid,
            "title": title_of(tex) or "Untitled paper",
            "updated": max(os.path.getmtime(_abs(run, main)),
                           os.path.getmtime(_state_path(run)) if os.path.exists(_state_path(run)) else 0),
            "imported": os.path.exists(os.path.join(run, "workspace", "imported")),
        })
    out.sort(key=lambda p: p["updated"], reverse=True)
    return out[:30]


def delete_project(runs_root: str, pid: str) -> str:
    """Move a project to runs/_deleted/ (not erased, so it can be recovered). Returns the new folder."""
    if not PID_RE.match(pid or ""):
        raise WorkspaceError("Unknown project.", 404)
    src = os.path.join(runs_root, pid)
    if not os.path.isdir(src):
        raise WorkspaceError("This paper no longer exists.", 404)
    if pid in _busy:
        raise WorkspaceError("The chat is still working on this paper. Stop it first.", 409)
    trash = os.path.join(runs_root, "_deleted")
    os.makedirs(trash, exist_ok=True)
    dst, n = os.path.join(trash, pid), 2
    while os.path.exists(dst):
        dst, n = os.path.join(trash, f"{pid}-{n}"), n + 1
    try:
        shutil.move(src, dst)
    except OSError as e:
        raise WorkspaceError(f"Couldn't move the folder (is a file from it open in another program?): {e}", 409)
    return dst


def _pdf_for(run: str, main: str) -> str:
    return os.path.join(_paper(run), os.path.splitext(posixpath.basename(main))[0] + ".pdf")


def summary(run: str) -> dict:
    state = load_state(run)
    pdf = _pdf_for(run, state["main"])
    return {
        "id": os.path.basename(run),
        "title": title_of(_read(_abs(run, state["main"]), 30_000)) or "Untitled paper",
        "main": state["main"],
        "main_candidates": _main_candidates(run),
        "files": list_files(run),
        "version": state["version"],
        "versions": state["versions"],
        "messages": state["messages"],
        "cost": round(state.get("cost", 0.0), 4),
        "compile": state.get("compile"),
        "pdf": os.path.exists(pdf),
        "pdf_mtime": os.path.getmtime(pdf) if os.path.exists(pdf) else 0,
        "has_inputs": os.path.exists(os.path.join(run, "inputs", "idea.md")),
        "busy": os.path.basename(run) in _busy,
        "run_dir": run,
        "latex": latex.status(),
    }


def pdf_path(run: str) -> str | None:
    path = _pdf_for(run, load_state(run)["main"])
    return path if os.path.exists(path) else None


def read_file(run: str, rel: str) -> dict:
    rel = safe_rel(rel)
    path = _abs(run, rel)
    if not os.path.isfile(path):
        raise WorkspaceError(f"'{rel}' doesn't exist.", 404)
    if not is_text(rel) or os.path.getsize(path) > MAX_TEXT:
        raise WorkspaceError(f"'{rel}' can't be opened as text.", 415)
    return {"path": rel, "text": _read(path)}


def raw_path(run: str, rel: str) -> str:
    path = _abs(run, rel)
    if not os.path.isfile(path):
        raise WorkspaceError("File not found.", 404)
    return path


