"""Projects on disk: paths, the file list, state, versions, listing, and changes made by hand."""

import difflib
import json
import os
import posixpath
import re
import shutil
import threading
import time

from .. import ingest, latex, llm


PID_RE = re.compile(r"^\d{8}-\d{6}-[0-9a-f]{8}$")
TEXT_EXT = {".tex", ".bib", ".sty", ".cls", ".bst", ".txt", ".md", ".csv", ".tsv", ".json", ".cfg", ".def", ".clo",
            ".bbx", ".cbx", ".lbx", ".dtx", ".ins", ".ltx", ".tikz", ".yaml", ".yml", ".bbl"}
BUILD_EXT = (".aux", ".log", ".out", ".blg", ".fls", ".fdb_latexmk", ".synctex.gz", ".toc", ".lof", ".lot", ".xdv",
             ".nav", ".snm", ".vrb", ".run.xml", ".bcf", ".tmp")
IMAGE_EXT = {".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp"}
MAX_TEXT = 2_000_000                 # larger text files are not versioned or edited
MAX_UPLOAD = 50 * 1024 * 1024
MAX_CONTEXT_CHARS = 600_000          # project text sent to the model per request
MAX_INPUT_CHARS = 150_000
HISTORY_TURNS = 8
_busy: dict[str, llm.Job] = {}
_busy_guard = threading.Lock()


class WorkspaceError(Exception):
    def __init__(self, msg: str, code: int = 400):
        super().__init__(msg)
        self.code = code


# --------------------------------------------------------------------------- #
# Paths and files
# --------------------------------------------------------------------------- #
def run_dir(runs_root: str, pid: str) -> str:
    if not PID_RE.match(pid or ""):
        raise WorkspaceError("Unknown project.", 404)
    path = os.path.join(runs_root, pid)
    if not os.path.isdir(os.path.join(path, "paper")):
        raise WorkspaceError("This project has no paper yet.", 404)
    return path


def _paper(run: str) -> str:
    return os.path.join(run, "paper")


def safe_rel(rel: str) -> str:
    """Normalise a project-relative path; refuse anything that could leave the project folder."""
    rel = (rel or "").replace("\\", "/").strip().strip("/")
    norm = posixpath.normpath(rel) if rel else ""
    parts = norm.split("/")
    if (not norm or norm == "." or norm.startswith("../") or norm == ".." or ":" in parts[0]
            or any(p.startswith(".") or p == "__MACOSX" for p in parts)):
        raise WorkspaceError(f"'{rel}' is not a valid file name.")
    return norm


def _abs(run: str, rel: str) -> str:
    return os.path.join(_paper(run), *safe_rel(rel).split("/"))


def _ext(rel: str) -> str:
    low = rel.lower()
    return ".synctex.gz" if low.endswith(".synctex.gz") else os.path.splitext(low)[1]


def is_text(rel: str) -> bool:
    return _ext(rel) in TEXT_EXT


def _read(path: str, limit: int | None = None) -> str:
    if not os.path.exists(path):
        return ""
    with open(path, encoding="utf-8", errors="replace") as f:
        text = f.read()
    return text[:limit] if limit else text


def _write(path: str, text: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, path)


def _all_files(run: str) -> list[str]:
    paper, out = _paper(run), []
    for root, dirs, files in os.walk(paper):
        dirs[:] = [d for d in dirs if not d.startswith(".") and d != "__MACOSX"]
        for name in files:
            if name.startswith(".") or name.endswith(".tmp"):
                continue
            out.append(os.path.relpath(os.path.join(root, name), paper).replace("\\", "/"))
    return sorted(out, key=str.lower)


def _hidden(rel: str, all_set: set) -> bool:
    """Build outputs: aux/log files and the PDF next to a .tex file of the same name."""
    low = rel.lower()
    if low.endswith(BUILD_EXT):
        return True
    if low.endswith(".bbl"):  # generated by bibtex, unless the project ships it instead of a .bib
        return any(f.lower().endswith(".bib") for f in all_set)
    if low.endswith(".pdf"):
        stem = rel[:-4]
        if stem + ".tex" in all_set:
            return True
        if "/" not in rel:  # compiled output of a main file that lives in a subfolder
            return any(f.endswith("/" + stem + ".tex") for f in all_set)
    return False


def list_files(run: str) -> list[dict]:
    files = _all_files(run)
    all_set = set(files)
    out = []
    for rel in files:
        if _hidden(rel, all_set):
            continue
        ext = _ext(rel)
        kind = ("tex" if ext == ".tex" else "bib" if ext == ".bib" else "text" if ext in TEXT_EXT
                else "image" if ext in IMAGE_EXT else "pdf" if ext == ".pdf" else "other")
        size = os.path.getsize(_abs(run, rel))
        out.append({"path": rel, "size": size, "kind": kind, "editable": kind in ("tex", "bib", "text") and size <= MAX_TEXT})
    return out


def _snapshot(run: str) -> dict[str, str]:
    snap = {}
    for f in list_files(run):
        if f["editable"]:
            snap[f["path"]] = _read(_abs(run, f["path"]))
    return snap


def _main_candidates(run: str) -> list[str]:
    return [f["path"] for f in list_files(run)
            if f["kind"] == "tex" and "\\documentclass" in _read(_abs(run, f["path"]), 30_000)]


def _find_main(run: str) -> str | None:
    cands = _main_candidates(run)
    if not cands:
        return None
    if "main.tex" in cands:
        return "main.tex"
    try:
        return ingest._pick_main({c: _read(_abs(run, c), 30_000).encode() for c in cands})
    except ingest.InputError:
        return cands[0]


# --------------------------------------------------------------------------- #
# State and versions (each version is a snapshot of every text file)
# --------------------------------------------------------------------------- #
def _state_path(run: str) -> str:
    return os.path.join(run, "workspace", "state.json")


def _version_path(run: str, n: int) -> str:
    return os.path.join(run, "workspace", "versions", f"v{n:04d}.json")


def _write_version(run: str, n: int, files: dict, complete: bool = True):
    _write(_version_path(run, n), json.dumps({"complete": complete, "files": files}))


def _read_version(run: str, n: int) -> tuple[dict, bool]:
    path = _version_path(run, n)
    if not os.path.exists(path):
        raise WorkspaceError("That version doesn't exist.", 404)
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data["files"], data.get("complete", True)


def save_state(run: str, state: dict):
    _write(_state_path(run), json.dumps(state, indent=1))


def _migrate(run: str, state: dict) -> dict:
    """Older editor states kept only the main file per version; keep them as partial snapshots."""
    for v in state.get("versions", []):
        old = os.path.join(run, "workspace", "versions", f"v{v['n']:04d}.tex")
        if os.path.exists(old) and not os.path.exists(_version_path(run, v["n"])):
            _write_version(run, v["n"], {state["main"]: _read(old)}, complete=False)
    n = max([v["n"] for v in state.get("versions", [])] or [0]) + 1
    _write_version(run, n, _snapshot(run))
    state.setdefault("versions", []).append({"n": n, "note": "All project files", "time": time.time()})
    state.update(format=2, version=n)
    save_state(run, state)
    return state


def load_state(run: str, main: str | None = None) -> dict:
    path = _state_path(run)
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            state = json.load(f)
        if state.get("format") != 2:
            state = _migrate(run, state)
        if not os.path.exists(_abs(run, state["main"])):  # main file was deleted or renamed outside the app
            state["main"] = _find_main(run) or state["main"]
        return state
    main = main or _find_main(run)
    if not main:
        raise WorkspaceError("No .tex file with \\documentclass was found in this project.", 404)
    state = {"format": 2, "main": main, "messages": [], "version": 1, "cost": 0.0, "compile": None,
             "versions": [{"n": 1, "note": "Original", "time": time.time()}]}
    _write_version(run, 1, _snapshot(run))
    save_state(run, state)
    return state


def _commit(run: str, state: dict, note: str) -> int:
    n = max(v["n"] for v in state["versions"]) + 1
    _write_version(run, n, _snapshot(run))
    state["versions"].append({"n": n, "note": note[:120], "time": time.time()})
    state["version"] = n
    return n


def _event(state: dict, text: str, version: int | None = None):
    msg = {"role": "event", "text": text, "time": time.time()}
    if version:
        msg["version"] = version
    state["messages"].append(msg)


def _diff(old: dict, new: dict) -> dict:
    lines, added, removed, changed = [], 0, 0, []
    for path in sorted(set(old) | set(new), key=str.lower):
        a, b = old.get(path), new.get(path)
        if a == b:
            continue
        changed.append(path)
        label = " (new file)" if a is None else " (deleted)" if b is None else ""
        body = list(difflib.unified_diff((a or "").splitlines(), (b or "").splitlines(), lineterm="", n=1))[2:]
        added += sum(1 for l in body if l.startswith("+"))
        removed += sum(1 for l in body if l.startswith("-"))
        lines += [f"### {path}{label}"] + body
    return {"added": added, "removed": removed, "files": changed, "text": "\n".join(lines[:600])}


