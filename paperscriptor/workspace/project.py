# Read-only views
# --------------------------------------------------------------------------- #
def _braced(text: str, start: int) -> str:
    depth = 0
    for i in range(start, min(len(text), start + 2000)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
    return ""


def title_of(tex: str) -> str:
    m = re.search(r"\\title\s*(\[[^\]]*\])?\s*\{", tex)
    if not m:
        return ""
    t = _braced(tex, m.end() - 1)
    t = re.sub(r"\\(thanks|footnote)\s*\{.*", "", t, flags=re.S)
    t = re.sub(r"\\\\|\\newline", " ", t)
    t = re.sub(r"\\[a-zA-Z]+\*?(\[[^\]]*\])?", "", t)
    t = re.sub(r"[{}~]", " ", t)
    return re.sub(r"\s+", " ", t).strip()[:140]


def list_projects(runs_root: str) -> list[dict]:
    out = []
    if not os.path.isdir(runs_root):
        return out
    for pid in sorted(os.listdir(runs_root), reverse=True):
        run = os.path.join(runs_root, pid)
        if not PID_RE.match(pid) or not os.path.isdir(_paper(run)):
            continue
        main = None
        try:
            with open(_state_path(run), encoding="utf-8") as f:
                main = json.load(f).get("main")
        except (OSError, ValueError):
            main = "main.tex" if os.path.exists(os.path.join(_paper(run), "main.tex")) else _find_main(run)
        if not main or not os.path.exists(_abs(run, main)):
            continue
        tex = _read(_abs(run, main), 30_000)
        if "\\documentclass" not in tex:
            continue
        out.append({
            "id": pid,
            "title": title_of(tex) or "Untitled paper",
            "updated": max(os.path.getmtime(_abs(run, main)),
                           os.path.getmtime(_state_path(run)) if os.path.exists(_state_path(run)) else 0),
            "imported": os.path.exists(os.path.join(run, "workspace", "imported")),
        })
    out.sort(key=lambda p: p["updated"], reverse=True)
    return out[:30]


def delete_project(runs_root: str, pid: str) -> str:
    """Move a project to runs/_deleted/ (not erased, so it can be recovered). Returns the new folder."""
    if not PID_RE.match(pid or ""):
        raise WorkspaceError("Unknown project.", 404)
    src = os.path.join(runs_root, pid)
    if not os.path.isdir(src):
        raise WorkspaceError("This paper no longer exists.", 404)
    if pid in _busy:
        raise WorkspaceError("The chat is still working on this paper. Stop it first.", 409)
    trash = os.path.join(runs_root, "_deleted")
    os.makedirs(trash, exist_ok=True)
    dst, n = os.path.join(trash, pid), 2
    while os.path.exists(dst):
        dst, n = os.path.join(trash, f"{pid}-{n}"), n + 1
    try:
        shutil.move(src, dst)
    except OSError as e:
        raise WorkspaceError(f"Couldn't move the folder (is a file from it open in another program?): {e}", 409)
    return dst


def _pdf_for(run: str, main: str) -> str:
    return os.path.join(_paper(run), os.path.splitext(posixpath.basename(main))[0] + ".pdf")


def summary(run: str) -> dict:
    state = load_state(run)
    pdf = _pdf_for(run, state["main"])
    return {
        "id": os.path.basename(run),
        "title": title_of(_read(_abs(run, state["main"]), 30_000)) or "Untitled paper",
        "main": state["main"],
        "main_candidates": _main_candidates(run),
        "files": list_files(run),
        "version": state["version"],
        "versions": state["versions"],
        "messages": state["messages"],
        "cost": round(state.get("cost", 0.0), 4),
        "tokens": state.get("tokens") or {"input": 0, "output": 0, "reasoning": 0},
        "compile": state.get("compile"),
        "pdf": os.path.exists(pdf),
        "pdf_mtime": os.path.getmtime(pdf) if os.path.exists(pdf) else 0,
        "has_inputs": os.path.exists(os.path.join(run, "inputs", "idea.md")),
        "busy": os.path.basename(run) in _busy,
        "run_dir": run,
        "latex": latex.status(),
    }


def pdf_path(run: str) -> str | None:
    path = _pdf_for(run, load_state(run)["main"])
    return path if os.path.exists(path) else None


def read_file(run: str, rel: str) -> dict:
    rel = safe_rel(rel)
    path = _abs(run, rel)
    if not os.path.isfile(path):
        raise WorkspaceError(f"'{rel}' doesn't exist.", 404)
    if not is_text(rel) or os.path.getsize(path) > MAX_TEXT:
        raise WorkspaceError(f"'{rel}' can't be opened as text.", 415)
    return {"path": rel, "text": _read(path)}


def raw_path(run: str, rel: str) -> str:
    path = _abs(run, rel)
    if not os.path.isfile(path):
        raise WorkspaceError("File not found.", 404)
    return path


# --------------------------------------------------------------------------- #
# Changes made by hand
# --------------------------------------------------------------------------- #
def _check_main(state: dict, rel: str, text: str):
    if rel == state["main"] and ("\\documentclass" not in text or "\\end{document}" not in text):
        raise WorkspaceError(f"{rel} is the main file, and the change would remove \\documentclass or "
                             "\\end{document}, so it was not saved.")


def save_file(run: str, rel: str, text: str) -> dict:
    state = load_state(run)
    rel = safe_rel(rel)
    if not is_text(rel):
        raise WorkspaceError(f"'{rel}' can't be edited as text.")
    text = text.replace("\r\n", "\n")
    _check_main(state, rel, text)
    path = _abs(run, rel)
    if not os.path.exists(path) or _read(path) != text:
        _write(path, text)
        n = _commit(run, state, f"Edited {rel}")
        _event(state, f"You edited {rel} (version {n}).", n)
        save_state(run, state)
    return summary(run)


def new_file(run: str, rel: str) -> dict:
    state = load_state(run)
    rel = safe_rel(rel)
    if not is_text(rel):
        raise WorkspaceError("New files must be text files, such as .tex, .bib or .md.")
    path = _abs(run, rel)
    if os.path.exists(path):
        raise WorkspaceError(f"'{rel}' already exists.")
    _write(path, f"% {rel}\n" if rel.endswith(".tex") else "")
    n = _commit(run, state, f"Created {rel}")
    _event(state, f"Created {rel} (version {n}).", n)
    save_state(run, state)
    return summary(run)


def delete_file(run: str, rel: str) -> dict:
    state = load_state(run)
    rel = safe_rel(rel)
    if rel == state["main"]:
        raise WorkspaceError("This is the main file. Choose another main file first.")
    path = _abs(run, rel)
    if not os.path.isfile(path):
        raise WorkspaceError(f"'{rel}' doesn't exist.", 404)
    os.remove(path)
    n = _commit(run, state, f"Deleted {rel}")
    _event(state, f"Deleted {rel} (version {n})." + ("" if is_text(rel) else " Undo can't bring back non-text files."), n)
    save_state(run, state)
    return summary(run)


def upload(run: str, uploads: list[tuple[str, bytes]], folder: str = "") -> dict:
    state = load_state(run)
    if not uploads:
        raise WorkspaceError("Choose at least one file.")
    if sum(len(d) for _, d in uploads) > MAX_UPLOAD:
        raise WorkspaceError("The upload is larger than 50 MB.")
    folder = safe_rel(folder) if folder.strip("/ ") else ""
    names = []
    for name, data in uploads:
        rel = safe_rel(posixpath.join(folder, name.replace("\\", "/"))) if folder else safe_rel(name)
        path = _abs(run, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
        names.append(rel)
    n = _commit(run, state, f"Uploaded {len(names)} file(s)")
    shown = ", ".join(names[:4]) + (f" and {len(names) - 4} more" if len(names) > 4 else "")
    _event(state, f"Uploaded {shown} (version {n}).", n)
    save_state(run, state)
    return summary(run)


def set_main(run: str, rel: str) -> dict:
    state = load_state(run)
    rel = safe_rel(rel)
    if not rel.lower().endswith(".tex") or not os.path.isfile(_abs(run, rel)):
        raise WorkspaceError("Choose a .tex file.")
    if rel != state["main"]:
        state["main"], state["compile"] = rel, None
        _event(state, f"Main file is now {rel}.")
        save_state(run, state)
    return summary(run)


def restore(run: str, n: int) -> dict:
    state = load_state(run)
    files, complete = _read_version(run, n)
    current = _snapshot(run)
    for rel, text in files.items():
        _write(_abs(run, rel), text)
    if complete:
        for rel in current:
            if rel not in files and rel != state["main"]:
                os.remove(_abs(run, rel))
    if state["main"] not in files and complete:
        state["main"] = _find_main(run) or state["main"]
    m = _commit(run, state, f"Restored version {n}")
    _event(state, f"Went back to version {n} (saved as version {m}).", m)
    save_state(run, state)
    return summary(run)


def rename_file(run: str, rel: str, new_rel: str) -> dict:
    state = load_state(run)
    rel, new_rel = safe_rel(rel), safe_rel(new_rel)
    src, dst = _abs(run, rel), _abs(run, new_rel)
    if not os.path.isfile(src):
        raise WorkspaceError(f"'{rel}' doesn't exist.", 404)
    if os.path.exists(dst):
        raise WorkspaceError(f"'{new_rel}' already exists.")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    os.replace(src, dst)
    if state["main"] == rel:
        state["main"], state["compile"] = new_rel, None
    n = _commit(run, state, f"Renamed {rel} to {new_rel}")
    _event(state, f"Renamed {rel} to {new_rel} (version {n}). References to it in other files were not changed.", n)
    save_state(run, state)
    return summary(run)
